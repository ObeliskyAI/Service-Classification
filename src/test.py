from rapidfuzz import fuzz



def find_benefit_matches(notes, benefits, threshold=80):
    results = []

    for note in notes:
        note_lower = note.lower()
        matches = []

        for benefit in benefits:
            benefit_lower = benefit.lower()

            # 1. Exact substring match
            if benefit_lower in note_lower:
                score = 100

            # 2. Fuzzy partial match
            else:
                score = fuzz.partial_ratio(
                    benefit_lower,
                    note_lower
                )

            if score >= threshold:
                matches.append({
                    "benefit": benefit,
                    "score": score
                })

        results.append({
            "note": note,
            "matches": matches
        })

    return results


